#!/bin/bash
# Puts the native layer's contract into a Chromium tree, for the hook's overlay
# files in chrome/browser/clair/ (change 1 design D1, task 9.2):
#
#   ClairHost.h          a copy of native/ClairHost.h, the header ClairUI is
#                        built against
#   ungoogled_version.h  the ungoogled-chromium version the host reports, from
#                        the submodule's chromium_version.txt and revision.txt
#
#   install-native-contract.sh <chromium-src> [repo-dir]
#
# Run after the overlay is copied: chrome/browser/clair/ must exist, and
# neither file may.

set -euo pipefail

die() {
  echo "install-native-contract: $1" >&2
  exit 1
}

[[ $# -ge 1 && $# -le 2 ]] || die "usage: install-native-contract.sh <chromium-src> [repo-dir]"
tree="$1"
repo="${2-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)}"
[[ -d "$tree" ]] || die "no Chromium tree at $tree"

dir="$tree/chrome/browser/clair"
[[ -d "$dir" && ! -L "$dir" ]] || die "chrome/browser/clair is missing; copy the overlay first"

header="$repo/native/ClairHost.h"
[[ -f "$header" ]] || die "no ClairHost.h at $header"

chromium="$(cat "$repo/ungoogled-chromium/chromium_version.txt" 2>/dev/null)" ||
  die "can't read ungoogled-chromium/chromium_version.txt"
revision="$(cat "$repo/ungoogled-chromium/revision.txt" 2>/dev/null)" ||
  die "can't read ungoogled-chromium/revision.txt"
# Both end up in a C string literal.
[[ "$chromium" =~ ^[0-9]+(\.[0-9]+){3}$ ]] || die "chromium_version.txt is not a Chromium version: $chromium"
[[ "$revision" =~ ^[0-9]+$ ]] || die "revision.txt is not a number: $revision"

for name in ClairHost.h ungoogled_version.h; do
  if [[ -e "$dir/$name" || -L "$dir/$name" ]]; then
    die "chrome/browser/clair/$name already exists; it comes from native/ and the submodule, not the overlay"
  fi
done

cp "$header" "$dir/ClairHost.h"
cat >"$dir/ungoogled_version.h" <<EOF
// Generated by Clair's scripts/install-native-contract.sh. Do not edit.

#ifndef CHROME_BROWSER_CLAIR_UNGOOGLED_VERSION_H_
#define CHROME_BROWSER_CLAIR_UNGOOGLED_VERSION_H_

#define CLAIR_UNGOOGLED_CHROMIUM_VERSION "$chromium-$revision"

#endif  // CHROME_BROWSER_CLAIR_UNGOOGLED_VERSION_H_
EOF
echo "install-native-contract: ClairHost.h and ungoogled_version.h ($chromium-$revision)"
